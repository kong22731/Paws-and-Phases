  const ALIEN = ['กรึ๊บ', 'ซ๊าาาก', 'ฟรื้ดดด', 'ขึกขึก', 'ญ๊าาา', 'ครืดดด', 'วี๊ดวี๊ด', '⟟⍜⏃', '☍⌇⟒', '⏚⟟⏁', 'ซึ่บบ', 'กึก...'];
