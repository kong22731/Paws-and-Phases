  function personaOf(pet) {
    if (!pet || !pet.line || pet.stage <= 1) return null;
    const p = PERSONAS[pet.line];
    return p ? p[pet.stage >= 4 ? 'high' : 'low'] : null;
  }

  // เปลี่ยนประโยคให้เข้ากับบุคลิกของร่างปัจจุบัน
  function voice(text, pet) {
    const ps = personaOf(pet);
    if (!ps || !text) return text;
    if (ps.gibberish) {
      // เอเลี่ยน: พูดไม่รู้เรื่องเลย (ความยาวพอ ๆ กับประโยคเดิม)
      const n = Math.max(2, Math.min(6, Math.round(text.length / 9)));
      const words = Array.from({ length: n }, () => pick(ALIEN));
      return words.join(' ') + (Math.random() < 0.5 ? '!' : '...') + ' ' + pick(ALIEN_ACT);
    }
    let t = text;
    if (ps.me) t = t.replace(/เรา(?!ะ)/g, ps.me); // ไม่แตะคำว่า "หัวเราะ"
    if (ps.you) t = t.replace(/เธอ/g, ps.you);
    if (ps.slow) t = t.replace(/ (?!ๆ)/g, '... ').replace(/[!！]/g, '...');
    if (t.startsWith('(') && t.endsWith(')')) return t; // ท่าทางล้วน ไม่ต้องเติมคำ
    return (ps.pre ? pick(ps.pre) : '') + t + (ps.post ? pick(ps.post) : '');
  }

